use super::auth::LocalSessionState;
use crate::commands::critical::{purchase_inventory_paid_factor, user_can_view_purchases};
use serde::{Deserialize, Serialize};
use sqlx::sqlite::SqliteConnectOptions;
use sqlx::{Connection, Row, SqliteConnection};
use std::collections::HashSet;
use tauri::{Manager, State};
use uuid::Uuid;

const LOCAL_PHARMACY: &str = "local_default";

#[derive(Clone, Debug, Deserialize)]
pub struct PurchaseReturnPayload {
    pub purchase_invoice_id: String,
    pub supplier_id: i64,
    pub user_id: String,
    pub pharmacy_id: Option<String>,
    pub reason: Option<String>,
    pub refund_method: String,
    pub items: Vec<PurchaseReturnItem>,
}

#[derive(Clone, Debug, Deserialize)]
pub struct PurchaseReturnItem {
    pub purchase_invoice_item_id: i64,
    pub quantity: f64,
    pub unit: Option<String>,
}

#[derive(Debug, Serialize)]
pub struct PurchaseReturnResult {
    pub return_id: String,
    pub total_amount: f64,
}

struct PreparedLine {
    purchase_invoice_item_id: i64,
    inventory_id: String,
    drug_id: i64,
    drug_name: String,
    quantity: f64,
    unit: String,
    unit_price: f64,
    total_price: f64,
    stock_quantity: f64,
}

#[tauri::command]
pub async fn create_purchase_return_critical(
    app: tauri::AppHandle,
    session: State<'_, LocalSessionState>,
    payload: PurchaseReturnPayload,
    request_id: String,
) -> Result<PurchaseReturnResult, String> {
    let _actor_guard = session.authorize_actor(&payload.user_id).await?;
    let path = app
        .path()
        .app_data_dir()
        .map_err(|error| error.to_string())?
        .join("pharma_local.db");
    let options = SqliteConnectOptions::new()
        .filename(path)
        .create_if_missing(true)
        .foreign_keys(true);
    let mut connection = SqliteConnection::connect_with(&options)
        .await
        .map_err(|error| error.to_string())?;
    sqlx::query("PRAGMA busy_timeout = 5000")
        .execute(&mut connection)
        .await
        .map_err(|error| error.to_string())?;
    run_purchase_return_with_request(&mut connection, payload, &request_id).await
}

pub(crate) async fn run_purchase_return_transaction(
    connection: &mut SqliteConnection,
    payload: PurchaseReturnPayload,
) -> Result<PurchaseReturnResult, String> {
    // Only internal synthetic callers use an autogenerated nonce.
    // The renderer-exposed command MUST supply a persistent UUIDv4 request ID.
    run_purchase_return_with_request(connection, payload, &Uuid::new_v4().to_string()).await
}

async fn run_purchase_return_with_request(
    connection: &mut SqliteConnection,
    payload: PurchaseReturnPayload,
    request_id: &str,
) -> Result<PurchaseReturnResult, String> {
    let parsed = Uuid::parse_str(request_id)
        .map_err(|_| "Purchase return requestId must be a canonical UUIDv4")?;
    if parsed.get_version_num() != 4 || parsed.to_string() != request_id {
        return Err("Purchase return requestId must be a canonical UUIDv4".into());
    }
    // ponytail: BEGIN IMMEDIATE serializes validation with the stock/accounting write.
    sqlx::query("BEGIN IMMEDIATE")
        .execute(&mut *connection)
        .await
        .map_err(|error| error.to_string())?;
    let result = create_purchase_return_with_request(connection, &payload, request_id).await;
    match result {
        Ok(result) => {
            let committed = sqlx::query("COMMIT").execute(&mut *connection).await;
            if let Err(error) = committed {
                // A deferred FK or I/O failure may leave SQLite inside its
                // write transaction. Never leak an open writer lease.
                let _ = sqlx::query("ROLLBACK").execute(&mut *connection).await;
                return Err(format!(
                    "Purchase return transaction commit failed: {error}"
                ));
            }
            Ok(result)
        }
        Err(error) => {
            let _ = sqlx::query("ROLLBACK").execute(&mut *connection).await;
            Err(error)
        }
    }
}

pub(crate) async fn create_purchase_return_on_connection(
    connection: &mut SqliteConnection,
    payload: &PurchaseReturnPayload,
) -> Result<PurchaseReturnResult, String> {
    create_purchase_return_with_request(connection, payload, &Uuid::new_v4().to_string()).await
}

async fn create_purchase_return_with_request(
    connection: &mut SqliteConnection,
    payload: &PurchaseReturnPayload,
    request_id: &str,
) -> Result<PurchaseReturnResult, String> {
    validate_payload(payload)?;

    let invoice = sqlx::query(
        r#"
        SELECT supplier_id, pharmacy_id, status, payment_method,
               CAST(COALESCE(tax_percent, 0) AS REAL) AS tax_percent,
               CAST(COALESCE(expenses, 0) AS REAL) AS expenses,
               CAST(COALESCE(discount_value, 0) AS REAL) AS discount_value,
               CAST(COALESCE(discount_percent, 0) AS REAL) AS discount_percent
        FROM purchase_invoices WHERE id = ?
        "#,
    )
    .bind(payload.purchase_invoice_id.trim())
    .fetch_optional(&mut *connection)
    .await
    .map_err(|error| error.to_string())?
    .ok_or_else(|| "Completed purchase invoice not found".to_string())?;
    let status: String = invoice.try_get("status").unwrap_or_default();
    if status != "completed" {
        return Err("Completed purchase invoice not found".into());
    }
    let supplier_id: i64 = invoice
        .try_get("supplier_id")
        .map_err(|_| "Purchase invoice has an invalid supplier".to_string())?;
    if supplier_id != payload.supplier_id {
        return Err("Purchase invoice does not belong to the selected supplier".into());
    }
    if sqlx::query("SELECT 1 FROM suppliers WHERE id = ?")
        .bind(supplier_id)
        .fetch_optional(&mut *connection)
        .await
        .map_err(|error| error.to_string())?
        .is_none()
    {
        return Err("Purchase invoice supplier no longer exists".into());
    }

    let invoice_pharmacy = normalize_pharmacy(
        invoice
            .try_get::<Option<String>, _>("pharmacy_id")
            .ok()
            .flatten()
            .as_deref(),
    );
    let session_pharmacy = normalize_pharmacy(payload.pharmacy_id.as_deref());
    if invoice_pharmacy != session_pharmacy {
        return Err("Purchase invoice belongs to another pharmacy".into());
    }
    // An absent historical branch cannot be promoted to trustworthy new
    // source-to-ledger ownership merely because the renderer says local_default.
    let stored_invoice_pharmacy: Option<String> =
        invoice.try_get("pharmacy_id").map_err(|e| e.to_string())?;
    if stored_invoice_pharmacy.as_deref() != Some(session_pharmacy.as_str())
        || session_pharmacy.trim().is_empty()
        || session_pharmacy == LOCAL_PHARMACY
    {
        return Err(
            "Unscoped historical purchase must be reconciled before a native return".into(),
        );
    }

    let user = sqlx::query(
        "SELECT id, pharmacy_id, role, permissions FROM users WHERE id = ? AND COALESCE(is_active, 1) = 1",
    )
    .bind(payload.user_id.trim())
    .fetch_optional(&mut *connection)
    .await
    .map_err(|error| error.to_string())?
    .ok_or_else(|| "Session user no longer exists or is inactive".to_string())?;
    let user_id: String = user
        .try_get("id")
        .map_err(|_| "Session user has an invalid identity".to_string())?;
    let user_role: Option<String> = user.try_get("role").unwrap_or(None);
    let user_permissions: Option<String> = user.try_get("permissions").unwrap_or(None);
    if !user_can_view_purchases(user_role.as_deref(), user_permissions.as_deref()) {
        return Err("Unauthorized: can_view_purchases permission required".into());
    }
    let user_pharmacy = normalize_pharmacy(
        user.try_get::<Option<String>, _>("pharmacy_id")
            .ok()
            .flatten()
            .as_deref(),
    );
    if user_pharmacy != session_pharmacy {
        return Err("Session pharmacy does not match the current user".into());
    }
    let stored_user_pharmacy: Option<String> =
        user.try_get("pharmacy_id").map_err(|e| e.to_string())?;
    if stored_user_pharmacy.as_deref() != Some(session_pharmacy.as_str()) {
        return Err("Unscoped actor cannot create a provenance-certified purchase return".into());
    }

    // The current licensed database has native purchase-create receipts (044)
    // and the corresponding initial purchase posting (042). An old invoice
    // row's mere presence under an explicit pharmacy text is NOT sufficient
    // custody to create a newly certified supplier refund. Do not trust the
    // less strict search UI as financial writer authorization. Legacy sources
    // without these receipts require an independent, signed reconciliation.
    let has_purchase_receipts: i64 = sqlx::query_scalar(
        "SELECT COUNT(*) FROM sqlite_master WHERE type='table' AND name='native_purchase_create_requests'",
    )
    .fetch_one(&mut *connection)
    .await
    .map_err(|error| error.to_string())?;
    if has_purchase_receipts != 0 {
        let native_origin: i64 = sqlx::query_scalar(
            "SELECT COUNT(*) FROM purchase_invoices p
             JOIN native_purchase_create_requests c ON c.invoice_id=p.id
             JOIN native_purchase_posting_events e ON e.journal_id=c.initial_journal_id
             WHERE p.id=? AND p.supplier_id=? AND p.pharmacy_id=? AND p.status='completed'
               AND CAST(p.user_id AS TEXT)=c.actor_id
               AND c.pharmacy_id=p.pharmacy_id AND c.supplier_id=p.supplier_id
               AND c.source_status='completed'
               AND c.source_line_count=(SELECT COUNT(*) FROM purchase_invoice_items i WHERE i.invoice_id=p.id)
               AND typeof(p.total_amount) IN ('integer','real')
               AND ABS(p.total_amount*100-c.source_total_cents)<0.0001
               AND e.invoice_id=p.id AND e.event_kind='initial'
               AND e.actor_id=c.actor_id AND e.pharmacy_id=c.pharmacy_id
               AND e.supplier_id=c.supplier_id
               AND e.payment_method=p.payment_method
               AND e.new_total_cents=c.source_total_cents
               AND (SELECT COUNT(*) FROM native_purchase_posting_events events WHERE events.invoice_id=p.id)=1",
        )
        .bind(payload.purchase_invoice_id.trim())
        .bind(supplier_id)
        .bind(&invoice_pharmacy)
        .fetch_one(&mut *connection)
        .await
        .map_err(|_| "Purchase return requires verifiable original 042/044 native provenance".to_string())?;
        if native_origin != 1 {
            return Err(
                "Purchase return requires verifiable original 042/044 native provenance".into(),
            );
        }
    }

    // Unreconciled finalized history may already have refunded this stock.
    // Do not certify another supplier refund from incomplete source amounts.
    let unreconciled_history: Option<i64> = sqlx::query_scalar(
        "SELECT 1 FROM purchase_returns pr
         LEFT JOIN purchase_return_items ri ON ri.purchase_return_id=pr.id
         WHERE pr.purchase_invoice_id=?
           AND lower(coalesce(pr.status,'')) IN ('completed','approved')
           AND (ri.id IS NULL OR NOT EXISTS (
             SELECT 1 FROM purchase_invoice_items pi
             WHERE pi.invoice_id=pr.purchase_invoice_id
               AND ((pi.id=ri.purchase_invoice_item_id
                   AND pi.inventory_id=ri.inventory_id AND pi.drug_id=ri.drug_id)
                 OR (ri.purchase_invoice_item_id IS NULL
                   AND pi.inventory_id=ri.inventory_id AND pi.drug_id=ri.drug_id))
           )
           OR typeof(pr.total_amount) NOT IN ('real','integer')
           OR abs(pr.total_amount - (
             SELECT COALESCE(SUM(item.total_price),0)
             FROM purchase_return_items item WHERE item.purchase_return_id=pr.id
           )) > 0.005
           OR (EXISTS (SELECT 1 FROM supplier_transactions st WHERE st.reference_id=pr.id)
             AND (COALESCE(pr.refund_method,'') NOT IN ('cash','credit')
               OR (SELECT COUNT(*) FROM supplier_transactions st WHERE st.reference_id=pr.id)
                 <> CASE WHEN pr.refund_method='cash' THEN 2 ELSE 1 END
               OR (SELECT COUNT(*) FROM supplier_transactions st
                   WHERE st.reference_id=pr.id AND st.supplier_id=pr.supplier_id
                     AND st.type='return' AND typeof(st.amount) IN ('real','integer')
                     AND abs(st.amount*100-pr.total_amount*100)<0.0001)<>1
               OR (pr.refund_method='cash' AND
                 (SELECT COUNT(*) FROM supplier_transactions st
                  WHERE st.reference_id=pr.id AND st.supplier_id=pr.supplier_id
                    AND st.type='payment' AND typeof(st.amount) IN ('real','integer')
                    AND abs(st.amount*100+pr.total_amount*100)<0.0001)<>1)
             ))) LIMIT 1",
    )
    .bind(payload.purchase_invoice_id.trim())
    .fetch_optional(&mut *connection)
    .await
    .map_err(|error| error.to_string())?;
    if unreconciled_history.is_some() {
        return Err(
            "Unresolved historical purchase return lineage, amount or historical supplier ledger; reconcile before posting".into(),
        );
    }

    let invoice_tax: f64 = invoice.try_get("tax_percent").unwrap_or(0.0);
    let invoice_expenses: f64 = invoice.try_get("expenses").unwrap_or(0.0);
    let invoice_discount_value: f64 = invoice.try_get("discount_value").unwrap_or(0.0);
    let invoice_discount_percent: f64 = invoice.try_get("discount_percent").unwrap_or(0.0);
    if !invoice_tax.is_finite()
        || invoice_tax < 0.0
        || !invoice_expenses.is_finite()
        || invoice_expenses < 0.0
        || !invoice_discount_value.is_finite()
        || invoice_discount_value < 0.0
        || !invoice_discount_percent.is_finite()
        || !(0.0..=100.0).contains(&invoice_discount_percent)
    {
        return Err("Purchase invoice has invalid stored totals".into());
    }
    let raw_items_total: f64 = sqlx::query_scalar(
        r#"
        SELECT CAST(COALESCE(SUM(
          CAST(quantity AS REAL) * CAST(cost_price AS REAL)
          * (1 + CAST(COALESCE(tax_percent, 0) AS REAL) / 100.0)
        ), 0) AS REAL)
        FROM purchase_invoice_items WHERE invoice_id = ?
        "#,
    )
    .bind(payload.purchase_invoice_id.trim())
    .fetch_one(&mut *connection)
    .await
    .map_err(|error| error.to_string())?;
    let taxed_items_total = raw_items_total * (1.0 + invoice_tax / 100.0);
    if !taxed_items_total.is_finite() || taxed_items_total <= 0.0 {
        return Err("Purchase invoice has no refundable item value".into());
    }
    let paid_factor = purchase_inventory_paid_factor(
        taxed_items_total,
        invoice_expenses,
        invoice_discount_value,
        invoice_discount_percent,
    );

    let mut prepared = Vec::with_capacity(payload.items.len());
    let mut total_amount = 0.0;
    let mut total_stock_value = 0.0;
    for item in &payload.items {
        let line = sqlx::query(
            r#"
            SELECT pii.id,
                   pii.drug_id,
                   CAST(pii.quantity AS REAL) AS purchased_quantity,
                   pii.inventory_id,
                   CAST(pii.cost_price AS REAL) AS cost_price,
                   CAST(COALESCE(pii.bonus_quantity, 0) AS REAL) AS bonus_quantity,
                   CAST(COALESCE(pii.tax_percent, 0) AS REAL) AS line_tax_percent,
                   CAST(COALESCE(pii.discount_percent, 0) AS REAL) AS line_discount_percent,
                   CAST(COALESCE(NULLIF(pii.strips_per_box, 0), NULLIF(md.large_to_medium, 0), 1) AS REAL) AS large_to_medium,
                   CAST(COALESCE(NULLIF(pii.medium_to_small, 0), NULLIF(md.medium_to_small, 0), 1) AS REAL) AS medium_to_small,
                   COALESCE(NULLIF(md.trade_name, ''), 'Drug ' || pii.drug_id) AS drug_name
            FROM purchase_invoice_items pii
            LEFT JOIN master_drugs md ON md.id = pii.drug_id
            WHERE pii.id = ? AND pii.invoice_id = ?
            "#,
        )
        .bind(item.purchase_invoice_item_id)
        .bind(payload.purchase_invoice_id.trim())
        .fetch_optional(&mut *connection)
        .await
        .map_err(|error| error.to_string())?
        .ok_or_else(|| {
            "One or more return lines do not belong to the selected purchase invoice".to_string()
        })?;

        let drug_id: i64 = line
            .try_get("drug_id")
            .map_err(|_| "Purchase invoice line has an invalid drug".to_string())?;
        let inventory_id = line
            .try_get::<Option<String>, _>("inventory_id")
            .ok()
            .flatten()
            .filter(|value| !value.trim().is_empty())
            .ok_or_else(|| {
                format!(
                    "Purchase invoice line {} has no inventory link",
                    item.purchase_invoice_item_id
                )
            })?;
        let purchased_quantity: f64 = line.try_get("purchased_quantity").unwrap_or(0.0);
        let cost_price: f64 = line.try_get("cost_price").unwrap_or(f64::NAN);
        let bonus_quantity: f64 = line.try_get("bonus_quantity").unwrap_or(0.0);
        let line_tax_percent: f64 = line.try_get("line_tax_percent").unwrap_or(0.0);
        let line_discount_percent: f64 = line.try_get("line_discount_percent").unwrap_or(0.0);
        let large_to_medium: f64 = line.try_get("large_to_medium").unwrap_or(1.0);
        let medium_to_small: f64 = line.try_get("medium_to_small").unwrap_or(1.0);
        if !purchased_quantity.is_finite()
            || purchased_quantity <= 0.0
            || !cost_price.is_finite()
            || cost_price < 0.0
            || !bonus_quantity.is_finite()
            || bonus_quantity < 0.0
            || !line_tax_percent.is_finite()
            || line_tax_percent < 0.0
            || !line_discount_percent.is_finite()
            || !(0.0..=100.0).contains(&line_discount_percent)
            || !large_to_medium.is_finite()
            || large_to_medium <= 0.0
            || !medium_to_small.is_finite()
            || medium_to_small <= 0.0
        {
            return Err(format!(
                "Purchase invoice line {} has invalid stored values",
                item.purchase_invoice_item_id
            ));
        }

        let unit = canonical_unit(item.unit.as_deref())?;
        let factor = match unit {
            "medium" => large_to_medium,
            "small" => large_to_medium * medium_to_small,
            _ => 1.0,
        };
        let returned_paid_quantity = item.quantity / factor;
        // Bonus stock carries the paid units' cost, so return it proportionally.
        let stock_quantity =
            returned_paid_quantity * ((purchased_quantity + bonus_quantity) / purchased_quantity);
        // cost_price is already post-line-discount in the purchase workflow.
        let paid_large_unit_price = cost_price
            * (1.0 + line_tax_percent / 100.0)
            * (1.0 + invoice_tax / 100.0)
            * paid_factor;
        let paid_line_total = purchased_quantity * paid_large_unit_price;
        let unit_price = paid_large_unit_price / factor;
        let total_price = item.quantity * unit_price;
        if !stock_quantity.is_finite() || !unit_price.is_finite() || !total_price.is_finite() {
            return Err("Purchase return calculation is invalid".into());
        }

        let prior = sqlx::query(
            r#"
            SELECT CAST(pri.quantity_returned AS REAL) AS quantity_returned,
                   COALESCE(pri.unit, 'large') AS unit,
                   CAST(COALESCE(pri.total_price, 0) AS REAL) AS total_price
            FROM purchase_return_items pri
            JOIN purchase_returns pr ON pr.id = pri.purchase_return_id
            WHERE pr.purchase_invoice_id = ?
              AND LOWER(COALESCE(pr.status, '')) IN ('completed', 'approved')
              AND (
                pri.purchase_invoice_item_id = ?
                OR (
                  pri.purchase_invoice_item_id IS NULL
                  AND pri.inventory_id = ?
                  AND pri.drug_id = ?
                )
              )
            "#,
        )
        .bind(payload.purchase_invoice_id.trim())
        .bind(item.purchase_invoice_item_id)
        .bind(&inventory_id)
        .bind(drug_id)
        .fetch_all(&mut *connection)
        .await
        .map_err(|error| error.to_string())?;
        let mut previously_returned = 0.0;
        let mut previous_refund = 0.0;
        for returned in prior {
            let quantity: f64 = returned.try_get("quantity_returned").unwrap_or(0.0);
            let previous_unit: String = returned.try_get("unit").unwrap_or_else(|_| "large".into());
            let previous_factor = match canonical_unit(Some(&previous_unit))? {
                "medium" => large_to_medium,
                "small" => large_to_medium * medium_to_small,
                _ => 1.0,
            };
            previously_returned += quantity / previous_factor;
            previous_refund += returned
                .try_get::<f64, _>("total_price")
                .unwrap_or(0.0)
                .max(0.0);
        }
        if previously_returned + returned_paid_quantity > purchased_quantity + 0.000_001 {
            let remaining = (purchased_quantity - previously_returned).max(0.0);
            return Err(format!(
                "Return quantity exceeds the invoice remainder ({remaining:.2} large units available)"
            ));
        }
        if previous_refund + total_price > paid_line_total + 0.005 {
            return Err(
                "Return value exceeds the amount paid for the purchase invoice line".into(),
            );
        }

        super::critical::ensure_exclusive_purchase_inventory(
            connection,
            &inventory_id,
            payload.purchase_invoice_id.trim(),
        )
        .await?;
        let inventory = sqlx::query(
            r#"
            SELECT CAST(quantity AS REAL) AS quantity,
                   CAST(cost_price AS REAL) AS cost_price
            FROM inventory
            WHERE id = ? AND drug_id = ?
              AND (pharmacy_id = ? OR (pharmacy_id IS NULL AND ? = 'local_default'))
            "#,
        )
        .bind(&inventory_id)
        .bind(drug_id)
        .bind(&invoice_pharmacy)
        .bind(&invoice_pharmacy)
        .fetch_optional(&mut *connection)
        .await
        .map_err(|error| error.to_string())?
        .ok_or_else(|| {
            "The purchase invoice inventory batch no longer exists in this pharmacy".to_string()
        })?;
        let available: f64 = inventory.try_get("quantity").unwrap_or(0.0);
        if available < stock_quantity {
            return Err(format!(
                "Insufficient inventory for {}",
                line.try_get::<String, _>("drug_name")
                    .unwrap_or_else(|_| format!("drug {drug_id}"))
            ));
        }
        let stock_cost: f64 = inventory.try_get("cost_price").unwrap_or(f64::NAN);
        if !stock_cost.is_finite() || stock_cost < 0.0 {
            return Err("Purchase inventory has an invalid carrying cost".into());
        }

        total_amount += total_price;
        total_stock_value += stock_quantity * stock_cost;
        prepared.push(PreparedLine {
            purchase_invoice_item_id: item.purchase_invoice_item_id,
            inventory_id,
            drug_id,
            drug_name: line
                .try_get("drug_name")
                .unwrap_or_else(|_| format!("Drug {drug_id}")),
            quantity: item.quantity,
            unit: unit.into(),
            unit_price,
            total_price,
            stock_quantity,
        });
    }
    if !total_amount.is_finite() {
        return Err("Purchase return total is invalid".into());
    }
    let amount_cents = certified_return_cents(total_amount)?;
    if !total_stock_value.is_finite() || (total_stock_value * 100.0).round() != amount_cents as f64
    {
        return Err(
            "Purchase return carrying value does not match supplier refund; reconcile inventory cost before posting".into(),
        );
    }
    // A return's source payment rail determines which liability/asset may be
    // reversed. The two legacy refund controls are NOT interchangeable: cash
    // on an unpaid credit invoice leaves the payable outstanding, and credit
    // on a cash-paid invoice creates a fictitious payable reversal. Bank and
    // mixed rail refunds require a distinct, source-bound implementation.
    let original_payment_method: Option<String> = invoice
        .try_get("payment_method")
        .map_err(|error| error.to_string())?;
    match original_payment_method.as_deref() {
        Some("credit") if payload.refund_method != "credit" => {
            return Err(
                "Credit purchase requires supplier settlement reconciliation before a cash refund"
                    .into(),
            );
        }
        Some("cash") if payload.refund_method != "cash" => {
            return Err("Cash-paid purchase cannot create a supplier payable credit return".into());
        }
        Some("bank") => {
            return Err(
                "Bank-paid purchase refund requires native bank settlement reconciliation".into(),
            );
        }
        Some("credit") => {
            // Global suppliers and supplier_transactions are historically
            // unscoped. Even an unreceipted prior payment changes the true
            // remaining obligation; it must not be silently ignored if it
            // predates the native 054 immutable rail.
            let unclassified_payment: i64 = sqlx::query_scalar(
                "SELECT COUNT(*) FROM supplier_transactions st
                 WHERE st.supplier_id=? AND st.type='payment'
                 AND NOT EXISTS (
                   SELECT 1 FROM purchase_returns pr
                   WHERE pr.id=st.reference_id AND pr.supplier_id=st.supplier_id
                     AND pr.refund_method='cash'
                 )",
            )
            .bind(supplier_id)
            .fetch_one(&mut *connection)
            .await
            .map_err(|error| error.to_string())?;
            if unclassified_payment != 0 {
                return Err("Credit purchase has supplier payment history requiring independent settlement reconciliation".into());
            }
            let balance: (f64, String) = sqlx::query_as(
                "SELECT CAST(balance AS REAL), typeof(balance) FROM suppliers WHERE id=?",
            )
            .bind(supplier_id)
            .fetch_one(&mut *connection)
            .await
            .map_err(|error| error.to_string())?;
            let remaining_cents = balance.0 * 100.0;
            if !matches!(balance.1.as_str(), "real" | "integer")
                || !remaining_cents.is_finite()
                || remaining_cents < amount_cents as f64 - 0.0001
                || (remaining_cents - remaining_cents.round()).abs() > 0.0001
            {
                return Err(
                    "Credit purchase return exceeds a provable outstanding supplier payable".into(),
                );
            }
        }
        Some("cash") => {}
        // A cheque, wallet, mixed, empty, or missing original payment rail
        // cannot be silently settled through the cash drawer or AP reduction.
        // Historic rows with unknown terms require independent source
        // reconciliation, even when a GUI displays a nominal tenant label.
        _ => return Err("Purchase return requires a provable original cash or credit payment rail".into()),
    }
    // The 054 rail can settle an invoice BEFORE a later supplier return. A
    // full credit return after a partial bank payment would debit the whole
    // refund to Accounts Payable, silently turning the already-paid portion
    // into a debit balance (an unclassified supplier advance). A cash return
    // would leave the unpaid invoice liability outstanding instead. Neither
    // may certify a receivable or release cash from this writer. Until a
    // source-bound paid-versus-unpaid split and supplier-credit settlement
    // journal exist, refuse ALL returns on a 054-settled invoice. Do this
    // before creating a return ID, inventory movement, ledger or nonce proof.
    let native_payment_rail_exists: bool = sqlx::query_scalar::<_, i64>(
        "SELECT COUNT(*) FROM sqlite_master WHERE type='table' AND name='native_supplier_payment_receipts'",
    )
    .fetch_one(&mut *connection)
    .await
    .map_err(|error| error.to_string())?
        != 0;
    if native_payment_rail_exists {
        let settlements: i64 = sqlx::query_scalar(
            "SELECT COUNT(*) FROM native_supplier_payment_receipts WHERE invoice_id=? AND supplier_id=?",
        )
        .bind(payload.purchase_invoice_id.trim())
        .bind(supplier_id)
        .fetch_one(&mut *connection)
        .await
        .map_err(|error| error.to_string())?;
        if settlements != 0 {
            return Err("Purchase invoice has receipted supplier payments; reconcile its paid portion and supplier receivable before a purchase return".into());
        }
    }
    let line_count = prepared.len();
    let mut proof_lines = Vec::with_capacity(line_count);

    let return_id = Uuid::new_v4().to_string();
    let reason = payload
        .reason
        .as_deref()
        .map(str::trim)
        .filter(|value| !value.is_empty());
    sqlx::query(
        r#"
        INSERT INTO purchase_returns
          (id, purchase_invoice_id, supplier_id, user_id, reason, total_amount, refund_method, status)
        VALUES (?, ?, ?, ?, ?, ?, ?, 'completed')
        "#,
    )
    .bind(&return_id)
    .bind(payload.purchase_invoice_id.trim())
    .bind(supplier_id)
    .bind(&user_id)
    .bind(reason)
    .bind(total_amount)
    .bind(&payload.refund_method)
    .execute(&mut *connection)
    .await
    .map_err(|error| error.to_string())?;

    for line in prepared {
        let stock = sqlx::query(
            r#"
            UPDATE inventory
            SET quantity = quantity - ?,
                updated_at = CURRENT_TIMESTAMP
            WHERE id = ? AND drug_id = ?
              AND (pharmacy_id = ? OR (pharmacy_id IS NULL AND ? = 'local_default'))
              AND quantity >= ?
            "#,
        )
        .bind(line.stock_quantity)
        .bind(&line.inventory_id)
        .bind(line.drug_id)
        .bind(&invoice_pharmacy)
        .bind(&invoice_pharmacy)
        .bind(line.stock_quantity)
        .execute(&mut *connection)
        .await
        .map_err(|error| error.to_string())?;
        if stock.rows_affected() != 1 {
            return Err(format!(
                "Inventory changed for {}; please retry",
                line.drug_name
            ));
        }

        let line_saved = sqlx::query(
            r#"
            INSERT INTO purchase_return_items
              (purchase_return_id, purchase_invoice_item_id, inventory_id, drug_id, drug_name,
               quantity_returned, unit_price, total_price, unit, reason)
            VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
            "#,
        )
        .bind(&return_id)
        .bind(line.purchase_invoice_item_id)
        .bind(&line.inventory_id)
        .bind(line.drug_id)
        .bind(&line.drug_name)
        .bind(line.quantity)
        .bind(line.unit_price)
        .bind(line.total_price)
        .bind(&line.unit)
        .bind(reason)
        .execute(&mut *connection)
        .await
        .map_err(|error| error.to_string())?;
        proof_lines.push((
            line_saved.last_insert_rowid(),
            line.purchase_invoice_item_id,
            line.inventory_id,
            line.quantity,
            line.stock_quantity,
            line.total_price,
        ));
    }

    let default_note = if payload.refund_method == "cash" {
        "Cash purchase return"
    } else {
        "Purchase return"
    };
    sqlx::query(
        "INSERT INTO supplier_transactions (supplier_id, type, amount, reference_id, notes, payment_method) VALUES (?, 'return', ?, ?, ?, ?)",
    )
    .bind(supplier_id)
    .bind(total_amount)
    .bind(&return_id)
    .bind(reason.unwrap_or(default_note))
    .bind(&payload.refund_method)
    .execute(&mut *connection)
    .await
    .map_err(|error| error.to_string())?;

    if payload.refund_method == "credit" {
        let updated =
            sqlx::query("UPDATE suppliers SET balance = COALESCE(balance, 0) - ? WHERE id = ?")
                .bind(total_amount)
                .bind(supplier_id)
                .execute(&mut *connection)
                .await
                .map_err(|error| error.to_string())?;
        if updated.rows_affected() != 1 {
            return Err("Purchase invoice supplier no longer exists".into());
        }
    } else {
        let permanent_shift_id = Uuid::new_v4().to_string();
        sqlx::query(
            r#"
            INSERT INTO shifts (id, user_id, pharmacy_id, status)
            SELECT ?, ?, ?, 'open'
            WHERE NOT EXISTS (
              SELECT 1
              FROM shifts s
              WHERE LOWER(COALESCE(s.status, '')) = 'open'
                AND COALESCE(NULLIF(TRIM(s.pharmacy_id), ''), 'local_default') = ?
            )
            "#,
        )
        .bind(&permanent_shift_id)
        .bind(&user_id)
        .bind(&invoice_pharmacy)
        .bind(&invoice_pharmacy)
        .execute(&mut *connection)
        .await
        .map_err(|error| error.to_string())?;
        let shift_id = sqlx::query_scalar::<_, String>(
            r#"
            SELECT s.id
            FROM shifts s
            WHERE LOWER(COALESCE(s.status, '')) = 'open'
              AND COALESCE(NULLIF(TRIM(s.pharmacy_id), ''), 'local_default') = ?
            ORDER BY s.rowid ASC
            LIMIT 1
            "#,
        )
        .bind(&invoice_pharmacy)
        .fetch_optional(&mut *connection)
        .await
        .map_err(|error| error.to_string())?;
        sqlx::query(
            r#"
            INSERT INTO cash_movements
              (id, user_id, shift_id, type, category, amount, notes, date,
               source_type, target_name, pharmacy_id)
            VALUES (?, ?, ?, 'receipt', 'purchase_return', ?, ?, DATE('now', 'localtime'),
                    'purchase_return', ?, ?)
            "#,
        )
        .bind(Uuid::new_v4().to_string())
        .bind(&user_id)
        .bind(shift_id)
        .bind(total_amount)
        .bind(reason.unwrap_or("Cash purchase return"))
        .bind(&return_id)
        .bind(&invoice_pharmacy)
        .execute(&mut *connection)
        .await
        .map_err(|error| error.to_string())?;
        sqlx::query(
            "INSERT INTO supplier_transactions (supplier_id, type, amount, reference_id, notes) VALUES (?, 'payment', ?, ?, 'Cash purchase return refund')",
        )
        .bind(supplier_id)
        .bind(-total_amount)
        .bind(&return_id)
        .execute(&mut *connection)
        .await
        .map_err(|error| error.to_string())?;
    }

    let journal_id = Uuid::new_v4().to_string();
    sqlx::query(
        "INSERT INTO daily_journals (id, date, description, created_by, total_amount, pharmacy_id) VALUES (?, DATE('now', 'localtime'), ?, ?, ?, ?)",
    )
    .bind(&journal_id)
    .bind(format!("Purchase return {return_id}"))
    .bind(&user_id)
    .bind(total_amount)
    .bind(&invoice_pharmacy)
    .execute(&mut *connection)
    .await
    .map_err(|error| error.to_string())?;
    let inventory_account = account_id(connection, "inventory_asset", "1.1.3").await?;
    let debit_account = if payload.refund_method == "credit" {
        account_id(connection, "accounts_payable", "2.1").await?
    } else {
        account_id(connection, "cash_drawer", "1.1.1").await?
    };
    insert_journal_entry(
        connection,
        &journal_id,
        debit_account,
        "debit",
        total_amount,
    )
    .await?;
    insert_journal_entry(
        connection,
        &journal_id,
        inventory_account,
        "credit",
        total_amount,
    )
    .await?;

    // Line witnesses are inserted BEFORE the parent receipt. SQLite's
    // deferred FK and parent INSERT guard require every posted source line to
    // be covered before the enclosing BEGIN IMMEDIATE can commit.
    for (line_id, purchase_line_id, lot_id, quantity, stock_quantity, refund_value) in proof_lines {
        sqlx::query(
            "INSERT INTO native_purchase_return_line_provenance
              (return_item_id,return_id,purchase_invoice_item_id,inventory_id,
               quantity_returned,stock_quantity,refund_value) VALUES(?,?,?,?,?,?,?)",
        )
        .bind(line_id)
        .bind(&return_id)
        .bind(purchase_line_id)
        .bind(lot_id)
        .bind(quantity)
        .bind(stock_quantity)
        .bind(refund_value)
        .execute(&mut *connection)
        .await
        .map_err(|error| format!("Cannot seal purchase return stock provenance: {error}"))?;
    }
    sqlx::query(
        "INSERT INTO native_purchase_return_provenance
          (return_id,request_id,purchase_invoice_id,pharmacy_id,actor_id,supplier_id,
           journal_id,refund_method,amount_cents,line_count)
         VALUES(?,?,?,?,?,?,?,?,?,?)",
    )
    .bind(&return_id)
    .bind(request_id)
    .bind(payload.purchase_invoice_id.trim())
    .bind(&invoice_pharmacy)
    .bind(&user_id)
    .bind(supplier_id)
    .bind(&journal_id)
    .bind(&payload.refund_method)
    .bind(amount_cents)
    .bind(line_count as i64)
    .execute(&mut *connection)
    .await
    .map_err(|error| format!("Cannot seal purchase return journal provenance: {error}"))?;
    sqlx::query(
        "INSERT INTO activity_log (user_id, pharmacy_id, action, details) VALUES (?, ?, 'PURCHASE_RETURN', ?)",
    )
    .bind(&user_id)
    .bind(&invoice_pharmacy)
    .bind(format!(
        "Purchase return {return_id} for supplier {supplier_id}; value={total_amount:.2}"
    ))
    .execute(&mut *connection)
    .await
    .map_err(|error| error.to_string())?;

    Ok(PurchaseReturnResult {
        return_id,
        total_amount,
    })
}

fn certified_return_cents(value: f64) -> Result<i64, String> {
    if !value.is_finite() || value <= 0.0 || value > 1_000_000_000_000.0 {
        return Err("Purchase return amount is not bounded for trustworthy posting".into());
    }
    let cents = value * 100.0;
    if !cents.is_finite() || (cents - cents.round()).abs() > 0.0001 {
        return Err("Purchase return amount requires an exact two-decimal posting".into());
    }
    Ok(cents.round() as i64)
}

