const MAX_LINES: usize = 100;
// Ensures every 100-line sum stays well inside the exact IEEE-754 integer
// range when converted from integer cents for the legacy REAL ledger columns.
const MAX_LINE_CENTS: i64 = 100_000_000_000;
const AUDIT_ACTION: &str = "CREATE_MANUAL_JOURNAL";

#[derive(Debug, Deserialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct ManualJournalLine {
    account_id: i64,
    #[serde(rename = "type")]
    entry_type: String,
    // String, never f64: JSON numbers and renderer rounding can silently
    // discard a third decimal place before the native validator sees it.
    amount: String,
    notes: Option<String>,
}

#[derive(Debug, Deserialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct ManualJournalInput {
    // A fresh, canonical lowercase UUID-v4 generated by the caller per write.
    // It is not a journal identifier or an authority-bearing selector.
    request_id: String,
    date: String,
    description: String,
    entries: Vec<ManualJournalLine>,
}

#[derive(Debug, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct ManualJournalPosted {
    id: String,
    total_amount: f64,
}

#[derive(Debug)]
struct ValidatedJournal {
    id: String,
    nonce: String,
    date: String,
    description: String,
    lines: Vec<ValidatedLine>,
    total_cents: i64,
}

#[derive(Debug)]
struct ValidatedLine {
    account_id: i64,
    entry_type: String,
    cents: i64,
    notes: Option<String>,
}

fn valid_date(value: &str) -> bool {
    if value.len() != 10
        || value.as_bytes()[4] != b'-'
        || value.as_bytes()[7] != b'-'
        || value
            .bytes()
            .enumerate()
            .any(|(index, byte)| index != 4 && index != 7 && !byte.is_ascii_digit())
    {
        return false;
    }
    let year = value[0..4].parse::<u32>().unwrap_or(0);
    let month = value[5..7].parse::<u32>().unwrap_or(0);
    let day = value[8..10].parse::<u32>().unwrap_or(0);
    let leap = year % 4 == 0 && (year % 100 != 0 || year % 400 == 0);
    let max_day = match month {
        1 | 3 | 5 | 7 | 8 | 10 | 12 => 31,
        4 | 6 | 9 | 11 => 30,
        2 if leap => 29,
        2 => 28,
        _ => 0,
    };
    year > 0 && day > 0 && day <= max_day
}

fn text_is_safe(value: &str, max_bytes: usize) -> bool {
    value.len() <= max_bytes
        && !value
            .chars()
            .any(|ch| ch == '\0' || (ch.is_control() && ch != '\n' && ch != '\r'))
}

fn exact_cents(amount: &str) -> Result<i64, String> {
    // Strict decimal transport: exactly two fractional digits, no scientific
    // notation, signed values, whitespace, separators, or rounding.
    let (whole, fraction) = amount
        .split_once('.')
        .ok_or("Journal amount must have exactly two decimal places")?;
    if whole.is_empty()
        || whole.len() > 12
        || fraction.len() != 2
        || !whole.bytes().all(|byte| byte.is_ascii_digit())
        || !fraction.bytes().all(|byte| byte.is_ascii_digit())
    {
        return Err("Journal amount must have exactly two decimal places".into());
    }
    let whole = whole
        .parse::<i64>()
        .map_err(|_| "Journal amount exceeds the safe limit")?;
    let fraction = fraction
        .parse::<i64>()
        .map_err(|_| "Invalid journal cents")?;
    let cents = whole
        .checked_mul(100)
        .and_then(|value| value.checked_add(fraction))
        .ok_or("Journal amount exceeds the safe limit")?;
    if !(1..=MAX_LINE_CENTS).contains(&cents) {
        return Err("Journal line amount must be positive and within the safe limit".into());
    }
    Ok(cents)
}

fn validate(input: ManualJournalInput) -> Result<ValidatedJournal, String> {
    let uuid = Uuid::parse_str(&input.request_id)
        .map_err(|_| "A fresh canonical UUID-v4 requestId is required")?;
    if uuid.get_version_num() != 4 || uuid.to_string() != input.request_id {
        return Err("A fresh canonical UUID-v4 requestId is required".into());
    }
    if !valid_date(&input.date) {
        return Err("Invalid manual journal date".into());
    }
    if !text_is_safe(&input.description, 2000) {
        return Err("Invalid manual journal description".into());
    }
    if !(2..=MAX_LINES).contains(&input.entries.len()) {
        return Err("Manual journals require between 2 and 100 entries".into());
    }

    let description = if input.description.trim().is_empty() {
        "قيد تسوية يدوي".to_owned()
    } else {
        input.description.trim().to_owned()
    };
    let mut debit: i64 = 0;
    let mut credit: i64 = 0;
    let mut lines = Vec::with_capacity(input.entries.len());
    for line in input.entries {
        if line.account_id <= 0
            || !matches!(line.entry_type.as_str(), "debit" | "credit")
            || line
                .notes
                .as_deref()
                .is_some_and(|notes| !text_is_safe(notes, 2000))
        {
            return Err("Invalid journal entry account, type, or notes".into());
        }
        let cents = exact_cents(&line.amount)?;
        let target = if line.entry_type == "debit" {
            &mut debit
        } else {
            &mut credit
        };
        *target = target
            .checked_add(cents)
            .ok_or("Manual journal total overflows integer cents")?;
        lines.push(ValidatedLine {
            account_id: line.account_id,
            entry_type: line.entry_type,
            cents,
            notes: line
                .notes
                .map(|text| text.trim().to_owned())
                .filter(|text| !text.is_empty()),
        });
    }
    if debit == 0 || debit != credit {
        return Err("Manual journal debit and credit totals must match in integer cents".into());
    }
    let nonce = uuid.to_string();
    Ok(ValidatedJournal {
        id: format!("manual-{nonce}"),
        nonce,
        date: input.date,
        description,
        lines,
        total_cents: debit,
    })
}

async fn journal_actor(conn: &mut SqliteConnection, actor_id: &str) -> Result<String, String> {
    // Must occur *inside* BEGIN IMMEDIATE to catch role changes, staff
    // disablement and pharmacy reassignment before any account is read/written.
    let (role, pharmacy) = active_generic_actor(conn, actor_id).await?;
    let actor = sqlx::query(
        "SELECT permissions,pharmacy_id FROM main.users WHERE CAST(id AS TEXT)=? AND COALESCE(is_active,1)=1",
    )
    .bind(actor_id)
    .fetch_one(&mut *conn)
    .await
    .map_err(|error| error.to_string())?;
    let permissions: Option<String> = actor.try_get("permissions").map_err(|error| error.to_string())?;
    let raw_pharmacy: Option<String> = actor.try_get("pharmacy_id").map_err(|error| error.to_string())?;
    // Neither a compatibility local_default label nor a later staff tenant
    // assignment proves the original owner of historic accounting sources.
    if raw_pharmacy.as_deref()!=Some(pharmacy.as_str()) || pharmacy.is_empty()
        || pharmacy.eq_ignore_ascii_case("local_default") {
        return Err("Manual journal requires an explicitly owned pharmacy".into());
    }
    let review:Option<i64>=sqlx::query_scalar(
        "SELECT 1 FROM main.native_owner_scope_review WHERE owner_id=? LIMIT 1"
    ).bind(actor_id).fetch_optional(&mut *conn).await.map_err(|error|error.to_string())?;
    if review.is_some() {
        return Err("Manual journal actor requires independent owner-scope review".into());
    }
    if !user_has_permission(
        Some(&role),
        permissions.as_deref(),
        "acc_can_make_daily_entries",
        false,
    ) {
        return Err("Authenticated user cannot create manual daily journals".into());
    }
    Ok(pharmacy)
}

fn audit_prefix(nonce: &str) -> String {
    format!("manual-journal-request={nonce};")
}

async fn post_with_lock(
    conn: &mut SqliteConnection,
    actor_id: &str,
    input: ManualJournalInput,
) -> Result<ManualJournalPosted, String> {
    let journal = validate(input)?;
    reset_cancelled_read_state(conn).await?;
    // sqlx Transaction rolls back even if the future is cancelled or dropped.
    let mut tx: Transaction<'_, Sqlite> =
        Transaction::begin(conn, Some(Cow::Borrowed("BEGIN IMMEDIATE")))
            .await
            .map_err(|error| error.to_string())?;
    let attempt = async {
        let conn = &mut *tx;
        let pharmacy = journal_actor(conn, actor_id).await?;
        let prefix = audit_prefix(&journal.nonce);
        // The audit row is a second, persistent replay witness in case a
        // journal is later removed by a permitted accounting correction.
        // BEGIN IMMEDIATE serializes simultaneous requests even without a
        // dedicated replay table. A future migration may add a unique index.
        let previously_audited: i64 = sqlx::query_scalar(
            "SELECT COUNT(*) FROM main.activity_log
             WHERE action='CREATE_MANUAL_JOURNAL'
               AND substr(details,1,length(?))=?
             LIMIT 1",
        )
        .bind(&prefix)
        .bind(&prefix)
        .fetch_one(&mut *conn)
        .await
        .map_err(|error| error.to_string())?;
        let already_posted: Option<String> =
            sqlx::query_scalar("SELECT id FROM main.daily_journals WHERE id=? LIMIT 1")
                .bind(&journal.id)
                .fetch_optional(&mut *conn)
                .await
                .map_err(|error| error.to_string())?;
        if previously_audited != 0 || already_posted.is_some() {
            return Err("Manual journal requestId has already been used".into());
        }

        for line in &journal.lines {
            let active_leaf: Option<i64> = sqlx::query_scalar(
                "SELECT a.id FROM main.accounts a
                 WHERE a.id=? AND COALESCE(a.is_group,0)=0
                   AND NOT EXISTS(SELECT 1 FROM main.accounts child WHERE child.parent_id=a.id)
                 LIMIT 1",
            )
            .bind(line.account_id)
            .fetch_optional(&mut *conn)
            .await
            .map_err(|error| error.to_string())?;
            if active_leaf.is_none() {
                return Err("Manual journal account is missing or not a postable leaf".into());
            }
        }

        sqlx::query(
            "INSERT INTO main.daily_journals
             (id,date,description,created_by,total_amount,pharmacy_id)
             VALUES (?,?,?,?,?,?)",
        )
        .bind(&journal.id)
        .bind(&journal.date)
        .bind(&journal.description)
        .bind(actor_id)
        .bind(journal.total_cents as f64 / 100.0)
        .bind(&pharmacy)
        .execute(&mut *conn)
        .await
        .map_err(|error| error.to_string())?;

        for line in &journal.lines {
            sqlx::query(
                "INSERT INTO main.journal_entries
                 (journal_id,account_id,type,amount,notes) VALUES(?,?,?,?,?)",
            )
            .bind(&journal.id)
            .bind(line.account_id)
            .bind(&line.entry_type)
            .bind(line.cents as f64 / 100.0)
            .bind(line.notes.as_deref().unwrap_or(&journal.description))
            .execute(&mut *conn)
            .await
            .map_err(|error| error.to_string())?;
        }

        let details = format!(
            "{} journal_id={}; total_cents={}",
            prefix, journal.id, journal.total_cents
        );
        sqlx::query(
            "INSERT INTO main.activity_log(user_id,action,details,pharmacy_id)
             VALUES(?,?,?,?)",
        )
        .bind(actor_id)
        .bind(AUDIT_ACTION)
        .bind(details)
        .bind(&pharmacy)
        .execute(&mut *conn)
        .await
        .map_err(|error| error.to_string())?;
        Ok(ManualJournalPosted {
            id: journal.id,
            total_amount: journal.total_cents as f64 / 100.0,
        })
    }
    .await;
    match attempt {
        Ok(posted) => {
            tx.commit().await.map_err(|error| error.to_string())?;
            Ok(posted)
        }
        Err(error) => {
            tx.rollback()
                .await
                .map_err(|rollback| format!("{error}; rollback failed: {rollback}"))?;
            Err(error)
        }
    }
}

#[tauri::command]
pub async fn create_manual_journal_native(
    app: tauri::AppHandle,
    session: State<'_, LocalSessionState>,
    payload: ManualJournalInput,
) -> Result<ManualJournalPosted, String> {
    let actor = session.authorize_session().await?;
    let pool = app
        .try_state::<GuardedReadPool>()
        .ok_or("Database initialization has not completed")?;
    let mut conn = pool.0.acquire().await.map_err(|error| error.to_string())?;
    post_with_lock(&mut conn, actor.as_deref().unwrap(), payload).await
}

