    #[tokio::test]
    async fn simultaneous_same_nonce_posts_only_one_voucher_under_writer_lock() {
        // A new unique throwaway temp database exercises distinct SQLite
        // connections and the real writer lock; no customer DB is opened.
        let mut path = std::env::temp_dir();
        path.push(format!(
            "pharma-manual-journal-test-{}.sqlite",
            Uuid::new_v4()
        ));
        let options = SqliteConnectOptions::new()
            .filename(&path)
            .create_if_missing(true)
            .busy_timeout(Duration::from_secs(8));
        let pool = SqlitePoolOptions::new()
            .max_connections(2)
            .connect_with(options)
            .await
            .unwrap();
        {
            let mut init = pool.acquire().await.unwrap();
            fixture(&mut init).await;
        }
        let (one, two) = tokio::join!(
            async {
                let mut conn = pool.acquire().await.unwrap();
                post_with_lock(&mut conn, "owner-a", input(REQUEST_ONE)).await
            },
            async {
                let mut conn = pool.acquire().await.unwrap();
                post_with_lock(&mut conn, "owner-a", input(REQUEST_ONE)).await
            }
        );
        assert_eq!(usize::from(one.is_ok()) + usize::from(two.is_ok()), 1);
        let mut conn = pool.acquire().await.unwrap();
        assert_eq!(count(&mut conn, "journals").await, 1);
        assert_eq!(count(&mut conn, "lines").await, 2);
        assert_eq!(count(&mut conn, "audit").await, 1);
        // Keep pool in this test scope only.
        drop(conn);
        pool.close().await;
        // Windows SQLite handles may be released just after pool.close().
        // Cleanup is best effort and must not fail a successful atomicity test.
        for _ in 0..20 {
            if std::fs::remove_file(&path).is_ok() {
                break;
            }
            tokio::time::sleep(Duration::from_millis(25)).await;
        }
    }

